use std::str::FromStr;

use super::{Mzml, MzmlMultistage};
use crate::{ChargeVec, Ms};

macro_rules! check_file {
    ($file:literal, $idx:literal, $mz:expr, $int:expr, $ty:ty, $pepmass:literal, $charge:literal, $rt:literal) => {
        let mzml = Mzml::from_str(&std::fs::read_to_string($file).unwrap());
        assert!(mzml.is_ok(), "{:?}", mzml);
        let mzml = mzml.unwrap();
        let spec = mzml.get($idx).unwrap();

        let mz = spec.pepmass();
        let charge = spec.charges();
        let rt = spec.retention_time();
        assert!(rt.is_some());
        let rt = rt.unwrap();

        let exp_charge = ChargeVec::from(vec![$charge]);

        assert_eq!(
            $mz,
            spec.iter().map(|peak| peak.mz as $ty).collect::<Vec<_>>()
        );
        assert_eq!(
            $int,
            spec.iter()
                .map(|peak| peak.intensity as $ty)
                .collect::<Vec<_>>()
        );
        assert_eq!($pepmass, mz);
        assert_eq!(exp_charge, *charge);
        assert_eq!($rt, rt);
    };
}

#[test]
fn parse_and_access_small_file_multistage() {
    let mzml_multistage =
        MzmlMultistage::from_str(&std::fs::read_to_string("test_files/mzml/small.mzml").unwrap());
    assert!(mzml_multistage.is_ok(), "{:?}", mzml_multistage);
    let mzml_multistage = mzml_multistage.unwrap();

    for spec_idx in 0..mzml_multistage.len() {
        let spec = mzml_multistage.get(spec_idx).unwrap();
        let product_ms_level = spec.ms_level().unwrap();
        if product_ms_level > 1 {
            let precursor_spec = mzml_multistage.get(spec.precursor_scan().unwrap()).unwrap();
            let precursor_ms_level = precursor_spec.ms_level().unwrap();
            // correctly correlated precursor-product spectra must differ by 1 ms level
            assert_eq!(precursor_ms_level + 1, product_ms_level);
        } else {
            // ms levels of 1 must not contain a precursor scan
            assert_eq!(spec.precursor_scan(), None);
        }
    }
}

