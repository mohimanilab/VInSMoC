#[test]
fn empty_binary() {
    let mzml =
        Mzml::from_str(&std::fs::read_to_string("test_files/mzml/empty_binary.mzML").unwrap());
    assert!(mzml.is_ok(), "{:?}", mzml);
    let mzml = mzml.unwrap();
    let spec = mzml.get(0).unwrap();
    assert_eq!(spec.iter().count(), 0);
}
