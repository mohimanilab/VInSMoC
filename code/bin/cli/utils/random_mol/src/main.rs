//! Utility to generate random molecules with a given formula.

use clap::Parser;
use molecule::{Atom, BondType, Mol, MolBuilder};
use petgraph::{
    graph::{EdgeReference, UnGraph},
    stable_graph::{NodeIndex, StableUnGraph},
    visit::EdgeRef,
};
use rand::{seq::IteratorRandom, Rng};

#[cfg(feature = "mimalloc")]
#[global_allocator]
static GLOBAL: mimalloc::MiMalloc = mimalloc::MiMalloc;

/// Utility to generate random molecules with the same formula as an input molecule.
///
/// After a --seed molecule is provided this program generates random graphs with the same atoms
/// until one that has a single connected component and no self-loops is generated. This molecule
/// is printed in SMILES format to stdout.
#[derive(Debug, Parser)]
#[clap(name = "random_mol", version = env!("CARGO_PKG_VERSION"))]
struct Opts {
    /// SMILES of the seed molecule to generate from.
    ///
    /// This SMILES should have no charges on its atoms, even if the final structure is neutral.
    #[clap(long, short = 's')]
    seed: String,
    #[clap(subcommand)]
    sub: Subcommand,
}

#[derive(Debug, Parser)]
enum Subcommand {
    /// Generate a random molecule using the pairing model.
    ///
    /// In the pairing model given a seed molecule a set of disconnected nodes corresponding to
    /// atoms in that molecule are created. Each of these nodes tracks the remaining available
    /// bonds. At each iteration two random nodes are selected and connected. This repeats until
    /// all nodes have no more space for edges. Afterwards the generated molecule is checked for
    /// connectedness and a lack of self-loops. If it fails these checks a new molecule is
    /// generated using the same process. This repeats until --max-attempts have been hit or a
    /// valid molecule is produced.
    PairingModel {
        /// Maximum number of times a valid molecule is attempted to be generated.
        ///
        /// If in this many attempts a valid molecule is not produced this tool will output an
        /// empty SMILES. If not specified there is no upper bound.
        #[clap(long)]
        max_attempts: Option<usize>,
    },
    /// Generate a random molecule using edge switches.
    EdgeSwitch {
        /// Number of edge switching operations to perform on the seed molecule.
        steps: usize,
    },
}

/// A node type used in graph construction, tracking the amount of available single bonds left to
/// this node.
#[derive(Debug, Clone, Copy)]
struct IntermediateNode {
    /// The number of single bonds that can be made to this node.
    stub: u8,
    /// The atom this node represents.
    atom: Atom,
}

impl IntermediateNode {
    /// Checks if this node has remaining capacity to form bonds.
    fn has_capacity(&self) -> bool {
        self.stub != 0
    }
}

/// Build a candidate undirected graph from the provided seed molecule.
///
/// This undirected graph will have the same degree sequence as the seed molecular graph, but could
/// have self loops. The assumption is that the input seed molecule has a single connected
/// component, but the graph generated by this function does not necessarily follow that
/// constraint. The input seed molecule should have explicit hydrogens.
///
/// Graph generation proceeds by using the configuration (or pairing) model. Initially isolated
/// nodes are created with stubs that allow for edge connections. Two nodes with remaining edge
/// capacity are randomly selected and connected until there are no available stubs left. The graph
/// is then returned.
fn build_graph(seed: &Mol) -> UnGraph<IntermediateNode, ()> {
    let mut rng = rand::thread_rng();
    let mut graph = UnGraph::<IntermediateNode, ()>::default();

    for node_index in seed.graph.node_indices() {
        let stub = seed
            .graph
            .edges(node_index)
            .map(|e| *e.weight() as u8)
            .sum::<u8>();
        let atom = seed.graph[node_index];
        graph.add_node(IntermediateNode { stub, atom });
    }

    while graph.node_weights().any(IntermediateNode::has_capacity) {
        let node1 = graph
            .node_indices()
            .filter(|&index| graph[index].has_capacity())
            .choose(&mut rng)
            .unwrap();
        graph[node1].stub -= 1;
        let node2 = graph
            .node_indices()
            .filter(|&index| graph[index].has_capacity())
            .choose(&mut rng)
            .unwrap();
        graph[node2].stub -= 1;
        graph.add_edge(node1, node2, ());
    }

    graph
}

/// Checks if the provided graph has any self loops.
fn has_self_loops(g: &UnGraph<IntermediateNode, ()>) -> bool {
    for index in g.node_indices() {
        if g.neighbors(index).any(|x| x == index) {
            return true;
        }
    }
    false
}

/// Builds a random molecule from the provided seed.
///
/// The built molecule will satisfy the following constraints:
/// - It will have the same degree sequence as the seed
/// - It will have the same molecular formula as the seed
/// - It will have one connected component
/// - It will have no self loops
///
/// This molecule is generated by repeated calls to [`build_graph`] until these constraints are
/// satisfied. The first two constraints are guaranteed, but the second two are checked each time.
///
/// The returned molecule has all of its hydrogens made implicit. The input seed molecule should
/// have explicit hydrogens.
///
/// # Logs
/// This prints the attempt count to stderr each time it calls [`build_graph`].
fn build_molecule(seed: &Mol, max_attempts: Option<usize>) -> Mol {
    let mut attempt = 0;
    eprintln!("Attempt {}", attempt);
    let mut graph = build_graph(seed);

    while petgraph::algo::connected_components(&graph) != 1 || has_self_loops(&graph) {
        if let Some(max) = max_attempts {
            if attempt > max {
                return Mol::default();
            }
        }
        attempt += 1;
        eprintln!("Attempt {}", attempt);
        graph = build_graph(seed);
    }

    let mut mol_graph = StableUnGraph::<Atom, BondType, u16>::default();
    for index in graph.node_indices() {
        mol_graph.add_node(graph[index].atom);
    }
    for x in graph.edge_references() {
        let mult = graph.edges_connecting(x.source(), x.target()).count() as u8;
        let start = x.source().index() as u16;
        let end = x.target().index() as u16;
        let bond_type = BondType::try_from(mult).expect("invalid multiplicity between two edges");
        if mol_graph.edges_connecting(start.into(), end.into()).count() == 0 {
            mol_graph.add_edge(start.into(), end.into(), bond_type);
        }
    }

    let mut mol = Mol::default();
    mol.graph = mol_graph;
    mol.implicit_hs();
    mol
}

/// Checks if the two provided edge references share any node endpoints.
fn shared_node(edge1: EdgeReference<BondType, u16>, edge2: EdgeReference<BondType, u16>) -> bool {
    edge1.source() == edge2.source()
        || edge1.source() == edge2.target()
        || edge1.target() == edge2.source()
        || edge1.target() == edge2.target()
}

/// Decrements the multiplicity of the edge with `index` in the provided `mol` graph.
///
/// Single bonds result in the removal of an edge. Double and triple bonds become single and double
/// bonds respectively. Aromatic bonds are not supported. Returns whether or not the operation was
/// successful, which is always true unless the edge with `index` is an aromatic bond.
fn decrement_bond(
    mol: &mut UnGraph<Atom, BondType, u16>,
    source: NodeIndex<u16>,
    target: NodeIndex<u16>,
) -> bool {
    let index = mol
        .find_edge(source, target)
        .expect("attempted to decrement non-existent bond");
    match mol[index] {
        BondType::Single => {
            mol.remove_edge(index);
        }
        BondType::Double => {
            mol[index] = BondType::Single;
        }
        BondType::Triple => {
            mol[index] = BondType::Double;
        }
        BondType::Aromatic => return false,
    };
    true
}

/// Increments the multiplicity of the edge connecting `a` and `b` in the provided `mol` graph.
///
/// If `a` and `b` are not already connected this creates a single bond connecting them. Single and
/// double bonds become double and triple bonds respectively. Aromatic bonds are not supported and
/// triple bonds cannot be further incremented. Returns whether or not the operation was
/// successful, which is always true unless there was already an aromatic or triple bond between
/// `a` and `b`.
fn increment_bond(
    mol: &mut UnGraph<Atom, BondType, u16>,
    a: NodeIndex<u16>,
    b: NodeIndex<u16>,
) -> bool {
    match mol.find_edge(a, b) {
        Some(index) => match mol[index] {
            BondType::Single => {
                mol[index] = BondType::Double;
            }
            BondType::Double => {
                mol[index] = BondType::Triple;
            }
            BondType::Triple | BondType::Aromatic => {
                return false;
            }
        },
        None => {
            mol.add_edge(a, b, BondType::Single);
        }
    }
    true
}

/// Attempts to perform a single edge-switch.
///
/// This functions returns whether or not the edge switching operation was a success. If this
/// returns false then the provided `mol` is unmodified, otherwise the `mol` will have the edge
/// switch operation applied in place. An edge switch can fail if:
/// - The selected edges share an endpoint
/// - The selected new edge to add already exists as an aromatic or triple bond
/// - The molecule has an aromatic bond
/// - The molecule after edge switching has more than one connected component
fn attempt_edge_switch(mol: &mut Mol) -> bool {
    let mut rng = rand::thread_rng();

    let mut graph = UnGraph::<Atom, BondType, u16>::from(mol.graph.clone());

    let edges = graph.edge_references().choose_multiple(&mut rng, 2);
    let edge1 = edges[0];
    let edge2 = edges[1];

    if shared_node(edge1, edge2) {
        return false;
    }

    let a = edge1.source();
    let b = edge1.target();
    let c = edge2.source();
    let d = edge2.target();

    if rng.gen_bool(0.5) {
        // a,c and b,d
        if !increment_bond(&mut graph, a, c) {
            return false;
        }
        if !increment_bond(&mut graph, b, d) {
            return false;
        }
        decrement_bond(&mut graph, a, b);
        decrement_bond(&mut graph, c, d);
    } else {
        // a,d and b,c
        if !increment_bond(&mut graph, a, d) {
            return false;
        }
        if !increment_bond(&mut graph, b, c) {
            return false;
        }
        decrement_bond(&mut graph, a, b);
        decrement_bond(&mut graph, c, d);
    }

    if petgraph::algo::connected_components(&graph) > 1 {
        return false;
    }

    mol.graph = graph.into();

    true
}

/// Perform `steps` edge switches on `mol`.
fn edge_switch(mol: &mut Mol, steps: usize) {
    for _ in 0..steps {
        while !attempt_edge_switch(mol) {}
    }
}

fn main() -> anyhow::Result<()> {
    let opts = Opts::parse();

    let mut seed = MolBuilder::from_smiles(&opts.seed)?.explicit_hs().build();

    match opts.sub {
        Subcommand::PairingModel { max_attempts } => {
            let mol = build_molecule(&seed, max_attempts);
            println!("{}", mol.to_smiles());
        }
        Subcommand::EdgeSwitch { steps } => {
            edge_switch(&mut seed, steps);
            seed.implicit_hs();
            println!("{}", seed.to_smiles());
        }
    };

    Ok(())
}
